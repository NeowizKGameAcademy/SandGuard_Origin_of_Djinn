/// <summary>포인트를 써서 선택한 스킬을 배운다.</summary>
/// <remarks>
/// 스킬 선택 화면에서 쓴다. 필요한 앞 단계 스킬과 남은 포인트를 다시 확인한다.
/// 실패하면 포인트나 능력치가 바뀌면 안 된다. 이미 배운 스킬은 중복 결제하지 않는다.
/// </remarks>
public interface ISkillTreeCommands
{
    /// <summary>포인트를 써서 지정한 스킬을 배운다.</summary>
    /// <remarks>
    /// 스킬이 있는지, 먼저 배워야 할 스킬을 배웠는지, 포인트와 현재 게임 상태가 맞는지 다시 확인한다.
    /// 이미 배웠으면 AlreadyLearned로 실패한다. 포인트를 또 쓰거나 효과를 또 적용하거나 알림을 또 보내지 않는다.
    /// 다른 실패도 상태를 바꾸지 않는다. 성공하면 모든 변경을 끝낸 뒤 관련 알림을 보낸다.
    /// 알림을 받은 코드가 다른 명령을 보내면 순서대로 처리한다. 이전 게임에서 남은 작업은 재시작 후 적용하지 않는다.
    /// 포인트 지급량, 스킬 비용, 레벨 상한은 성장 데이터와 담당 코드에서 정한다.
    /// </remarks>
    ActionResult TryLearn(string nodeId);
}
