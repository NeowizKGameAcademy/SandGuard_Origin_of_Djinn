/// <summary>조건을 확인하고 마나를 써서 시설을 짓는다.</summary>
/// <remarks>
/// 슬롯 건설과 자유 배치 모두 이 기능으로 요청한다. 미리보기가 가능했어도 실제로 지을 때 다시 확인한다.
/// 실패하면 마나만 줄거나, 시설 없이 자리가 막히는 일이 없어야 한다.
/// </remarks>
public interface IFacilityBuilder
{
    /// <summary>조건을 다시 확인하고, 마나를 써서 시설을 짓는다.</summary>
    /// <remarks>
    /// 먼저 현재 게임 단계와 허용된 배치 방식부터 확인한다. 미리보기가 가능했다고 건설을 보장하지 않는다.
    /// 슬롯 요청은 SlotId로 현재 위치와 허용 시설을 찾고, 자유 배치 요청은 지정한 월드 위치를 검사한다.
    /// 두 방식 모두 같은 공간 충돌·생성·등록·철거 처리를 쓴다. 슬롯 사용 여부만 검사하면 자유 배치 시설과 겹칠 수 있다.
    /// 조건 확인, 마나 예약, 시설 생성·자리 확보·등록 준비, 최종 반영 순서로 처리한다.
    /// 준비 중인 시설과 자리는 외부에서 조회할 수 없게 한다. 실패할 수 있는 작업을 먼저 끝낸다.
    /// 성공 결과에는 화면에 표시할 FacilityViewData만 담는다. 시설을 바꾸는 기능은 넘기지 않는다.
    /// 모든 변경을 끝낸 뒤 알린다. 알림을 받은 코드가 다시 명령을 보내면 현재 작업이 끝난 뒤 순서대로 처리한다.
    /// 실패하면 준비한 시설과 자리를 정리하고 마나 예약을 푼다. Gain으로 환불하는 방법은 쓰지 않는다.
    /// </remarks>
    BuildResult TryBuild(PlacementRequest request);
}
