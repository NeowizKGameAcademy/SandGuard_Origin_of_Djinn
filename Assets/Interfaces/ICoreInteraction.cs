/// <summary>적이 코어에 도착했을 때 할 일을 정하고 처리한다.</summary>
/// <remarks>
/// 기본은 적을 흡수하고 코어 안정도를 깎는 방식이다. 적이 코어를 계속 공격하는 방식도 선택할 수 있게 둔다.
/// 흡수할 때는 적을 없애고 남은 적 수에도 반영한다. 공격 방식이면 여기서 피해를 주지 않고 적에게 공격하라고 알려 준다.
/// </remarks>
public interface ICoreInteraction
{
    /// <summary>흡수 방식인지 공격 방식인지 알려 준다. 한 게임을 시작할 때 정하고 도중에는 바꾸지 않는다.</summary>
    /// <remarks>
    /// 별도 설정이 없으면 도착 즉시 흡수하는 방식을 쓴다.
    /// </remarks>
    CoreInteractionMode Mode { get; }
    /// <summary>코어에 도착한 적을 흡수하거나, 코어를 공격하도록 알려 준다.</summary>
    /// <remarks>
    /// 현재 게임의 적인지, 살아 있는지, 적대 대상인지, 코어가 유효한지, 실제로 도착했는지 다시 확인한다.
    /// 길이 막혀 중간에 멈춘 것과 단순 충돌 알림만으로 도착했다고 판단하지 않는다.
    /// 흡수 방식은 정해진 코어 피해를 주고 적을 제거하며 남은 적 수에서도 한 번만 뺀다.
    /// 흡수를 사망으로 알리지 않는다. 이미 처리한 적이면 NoChange로 실패하고 다시 처리하지 않는다.
    /// 코어 안정도와 적의 상태·공격 가능 여부·제거를 모두 반영한 뒤 알림과 웨이브 완료를 처리한다.
    /// 마지막 적을 흡수하면서 코어가 파괴되면 승리보다 패배를 먼저 적용한다.
    /// 공격 방식은 AttackRequired만 돌려준다. 여기서 피해를 주거나 적을 없애거나 남은 적 수를 줄이지 않는다.
    /// 이 함수를 부른 쪽이 IAttackController로 코어를 공격하며, 맞히는 순간 조건을 다시 확인한다.
    /// 실패하면 코어·적·웨이브를 바꾸지 않는다. 일시정지 중에는 두 방식 모두 거부한다.
    /// </remarks>
    CoreArrivalResult TryHandleArrival(ICombatTarget enemy);
}
